  const pick = (list, random) => list[Math.floor(random() * list.length)];

  // План колоды: титул, разделитель посередине, финал — остальное тасуется
  // с оглядкой на то, чтобы карточки не шли подряд и ничто не повторялось трижды.
  function plan(count, random) {
    const head = pick(["T1", "T2"], random);
    const middle = [
      pick(["N1", "N2"], random),
      pick(["S1", "S2", "S3"], random),
      pick(["L1", "L2", "K1", "Q1", "TB1"], random),
    ];
    const rest = ["C1", "C2", "C3", "L1", "L2", "K1", "Q1", "TB1", "N1", "N2", "S1", "S2", "S3"];
    while (middle.length < Math.max(1, count - 3)) {
      const next = pick(rest, random);
      if (middle.filter((code) => code === next).length >= 2) continue;
      middle.push(next);
    }
    const cards = (code) => code === "C1" || code === "C2";
    const adjacent = (list) => list.some((code, i) => i > 0 && cards(code) && cards(list[i - 1]));
    for (let attempt = 0; attempt < 40; attempt++) {
      for (let i = middle.length - 1; i > 0; i--) {
        const j = Math.floor(random() * (i + 1));
        [middle[i], middle[j]] = [middle[j], middle[i]];
      }
      if (!adjacent(middle)) break;
    }
    // Разделитель встаёт в середину уже после тасовки: иначе он сам сдвигал
    // карточки друг к другу и рушил только что наведённый порядок.
    middle.splice(Math.max(1, Math.round(middle.length / 2)), 0, "R1");
    return [head, ...middle, "Z1"];
  }

